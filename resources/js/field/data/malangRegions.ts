export const getDistrictsByCity = (cityName: string): DistrictData[] => {
  const city = MALANG_REGIONS.find((c) => c.name.toLowerCase() === cityName.toLowerCase());
  return city ? city.districts : [];
};

export const getVillagesByDistrict = (cityName: string, districtName: string): string[] => {
  const districts = getDistrictsByCity(cityName);
  const district = districts.find((d) => d.name.toLowerCase() === districtName.toLowerCase());
  return district ? district.villages : [];
};

export const formatFullAddress = (
  street: string,
  village: string,
  district: string,
  city: string
): string => {
  const parts: string[] = [];
  if (street.trim()) parts.push(street.trim());
  if (village.trim()) parts.push(`Desa/Kel. ${village.trim()}`);
  if (district.trim()) parts.push(`Kec. ${district.trim()}`);
  if (city.trim()) parts.push(city.trim());
  return parts.join(', ');
};
